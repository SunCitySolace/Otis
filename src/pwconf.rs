//! Generates the self-contained PipeWire drop-in (`99-otis-eq.conf`).
//!
//! Otis only ever writes or deletes this file; it is never parsed back.

use crate::dsp::{self, CROSSFEED_DELAY_US, CROSSFEED_HZ, CROSSFEED_Q};
use crate::model::Workspace;
use crate::preset::num;
use crate::store;
use std::{fs, io};

/// `node.name` of the virtual sink.
pub const SINK_NAME: &str = "otis_eq";
pub const SINK_DESCRIPTION: &str = "Otis EQ";
pub const KEY_MANAGED: &str = "otis.managed";
pub const KEY_HASH: &str = "otis.config_hash";
pub const KEY_TARGET: &str = "otis.target";

/// Deterministic hash of the active EQ + crossfeed + target: it is taken
/// over the generated filter graph and target, i.e. exactly what PipeWire
/// would run, so cosmetic edits (such as toggling a disabled band's gain)
/// do not count as unapplied changes.
pub fn config_hash(ws: &Workspace, target: &str) -> String {
    // Hash the normalised form, so a value that is mid-edit in the UI
    // hashes the same as the rounded value Apply would write.
    let mut ws = ws.clone();
    ws.normalize();
    let material = format!("{}\n{target}", filter_graph(&ws));
    // FNV-1a, 64 bit.
    let hash = material.bytes().fold(0xcbf2_9ce4_8422_2325u64, |h, b| (h ^ b as u64).wrapping_mul(0x0000_0100_0000_01b3));
    format!("{hash:016x}")
}

/// Full text of the drop-in for `ws`, pinned to hardware sink `target`.
pub fn render(ws: &Workspace, target: &str) -> String {
    let hash = config_hash(ws, target);
    let target = quote(target);
    format!(
        r#"# Generated by Otis. Do not edit: Otis overwrites this file on Apply
# and deletes it on Disable EQ.
context.modules = [
  {{ name = libpipewire-module-filter-chain
    flags = [ nofail ]
    args = {{
      node.description = "{SINK_DESCRIPTION}"
      media.name = "{SINK_DESCRIPTION}"
      audio.channels = 2
      audio.position = [ FL FR ]
      filter.graph = {{
{graph}      }}
      capture.props = {{
        node.name = "{SINK_NAME}"
        media.class = Audio/Sink
        {KEY_MANAGED} = "true"
        {KEY_HASH} = "{hash}"
        {KEY_TARGET} = {target}
      }}
      playback.props = {{
        node.name = "{SINK_NAME}.output"
        node.passive = true
        target.object = {target}
        node.dont-reconnect = true
      }}
    }}
  }}
]
"#,
        graph = filter_graph(ws),
    )
}

/// The `filter.graph` body: one `param_eq` node, plus the crossfeed
/// sub-graph (builtin `bq_lowpass`, `delay` and `mixer` nodes) when enabled.
fn filter_graph(ws: &Workspace) -> String {
    let pad = "        ";
    let mut nodes = format!("{pad}  {{ type = builtin name = eq label = param_eq\n{pad}    config = {{ filters = [\n");
    // param_eq's own convention for a preamp: a high shelf at 0 Hz.
    nodes += &format!("{pad}      {{ type = bq_highshelf freq = 0 gain = {:.1} q = 1.0 }}\n", ws.preamp_db());
    for b in ws.bands.iter().filter(|b| b.enabled) {
        let gain = if b.kind.has_gain() { b.gain } else { 0.0 };
        nodes += &format!(
            "{pad}      {{ type = {} freq = {} gain = {gain:.1} q = {:.2} }}\n",
            b.kind.pipewire_label(),
            num(b.freq, 1),
            b.q,
        );
    }
    nodes += &format!("{pad}    ] }}\n{pad}  }}\n");

    if !ws.crossfeed.enabled {
        return format!(
            "{pad}nodes = [\n{nodes}{pad}]\n{pad}inputs = [ \"eq:In 1\" \"eq:In 2\" ]\n{pad}outputs = [ \"eq:Out 1\" \"eq:Out 2\" ]\n"
        );
    }

    let (direct, cross) = dsp::crossfeed_gains(ws.crossfeed.feed_db);
    let delay = CROSSFEED_DELAY_US / 1e6;
    let mut links = String::new();
    // Each output mixes its own channel with the low-passed, delayed
    // opposite channel: (side, eq port, opposite side).
    for (side, port, other) in [("L", 1, "R"), ("R", 2, "L")] {
        nodes += &format!(
            "{pad}  {{ type = builtin name = lp{side} label = bq_lowpass control = {{ \"Freq\" = {CROSSFEED_HZ} \"Q\" = {CROSSFEED_Q} }} }}\n\
             {pad}  {{ type = builtin name = delay{side} label = delay config = {{ \"max-delay\" = 0.001 }} control = {{ \"Delay (s)\" = {delay:.6} }} }}\n\
             {pad}  {{ type = builtin name = mix{side} label = mixer control = {{ \"Gain 1\" = {direct:.6} \"Gain 2\" = {cross:.6} }} }}\n"
        );
        links += &format!(
            "{pad}  {{ output = \"eq:Out {port}\" input = \"mix{side}:In 1\" }}\n\
             {pad}  {{ output = \"eq:Out {port}\" input = \"lp{side}:In\" }}\n\
             {pad}  {{ output = \"lp{side}:Out\" input = \"delay{side}:In\" }}\n\
             {pad}  {{ output = \"delay{side}:Out\" input = \"mix{other}:In 2\" }}\n"
        );
    }
    format!(
        "{pad}nodes = [\n{nodes}{pad}]\n{pad}links = [\n{links}{pad}]\n{pad}inputs = [ \"eq:In 1\" \"eq:In 2\" ]\n{pad}outputs = [ \"mixL:Out\" \"mixR:Out\" ]\n"
    )
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

pub fn exists() -> bool {
    store::pipewire_conf().exists()
}

pub fn write(ws: &Workspace, target: &str) -> io::Result<()> {
    let path = store::pipewire_conf();
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    // Write-then-rename so PipeWire can never read a half-written file.
    let tmp = path.with_extension("conf.tmp");
    fs::write(&tmp, render(ws, target))?;
    fs::rename(tmp, path)
}

pub fn delete() -> io::Result<()> {
    match fs::remove_file(store::pipewire_conf()) {
        Err(e) if e.kind() != io::ErrorKind::NotFound => Err(e),
        _ => Ok(()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Band;

    fn sample() -> Workspace {
        let mut ws = Workspace::default();
        ws.bands.push(Band { gain: -4.0, q: 4.5, ..Band::peak(6400.0) });
        ws.bands.push(Band { enabled: false, gain: 9.0, ..Band::peak(100.0) });
        ws
    }

    #[test]
    fn renders_param_eq_with_tags_and_pinning() {
        let conf = render(&sample(), "alsa_output.usb-dac");
        assert!(conf.contains("{ type = bq_peaking freq = 6400 gain = -4.0 q = 4.50 }"));
        assert!(conf.contains("{ type = bq_highshelf freq = 0 gain = 0.0 q = 1.0 }"));
        assert!(!conf.contains("freq = 100 "), "disabled bands are not emitted");
        assert!(conf.contains("target.object = \"alsa_output.usb-dac\""));
        assert!(conf.contains("node.dont-reconnect = true"));
        assert!(conf.contains("otis.managed = \"true\""));
        assert!(!conf.contains("links"));
        assert_eq!(conf.matches('{').count(), conf.matches('}').count());
        assert_eq!(conf.matches('[').count(), conf.matches(']').count());
    }

    #[test]
    fn hash_tracks_audible_changes_only() {
        let ws = sample();
        let hash = config_hash(&ws, "a");
        assert_eq!(hash, config_hash(&ws.clone(), "a"));
        assert_ne!(hash, config_hash(&ws, "b"));

        let mut inaudible = ws.clone();
        inaudible.bands[1].gain = 1.0;
        assert_eq!(hash, config_hash(&inaudible, "a"));

        let mut crossfed = ws.clone();
        crossfed.crossfeed.enabled = true;
        assert_ne!(hash, config_hash(&crossfed, "a"));
        let conf = render(&crossfed, "a");
        assert!(conf.contains("\"Delay (s)\" = 0.000260"));
        assert!(conf.contains("outputs = [ \"mixL:Out\" \"mixR:Out\" ]"));
        assert_eq!(conf.matches('{').count(), conf.matches('}').count());

    }
}
